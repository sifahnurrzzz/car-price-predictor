@st.cache_resource
def load_model():
    try:
        model = joblib.load('car_price_model.pkl')
        features = joblib.load('features.pkl')
        return model, features
    except:
        # Fallback: buat model sederhana jika file tidak ditemukan
        from sklearn.linear_model import LinearRegression
        model = LinearRegression()
        # Train dengan data dummy
        X_dummy = np.array([[150, 3.0, 70, 3.0, 25],
                           [200, 3.5, 85, 3.5, 22],
                           [250, 4.0, 100, 4.0, 18],
                           [120, 2.0, 50, 2.5, 30]])
        y_dummy = np.array([25, 35, 50, 18])
        model.fit(X_dummy, y_dummy)
        features = ['Horsepower', 'Engine_size', 'Power_perf_factor', 'Curb_weight', 'Fuel_efficiency']
        return model, features

